    gbm, base = tm["gradient_boosting"], tm["pell_plus_sector_linear"]
    q_n = a1["median_n_entry_10mi_by_mobility_quintile"]
    cf = err[err["predictions"].str.startswith("cross-fitted")].set_index("group")
