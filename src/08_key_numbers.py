"""Step 8: collect every number quoted in the slides, README and video script into one file.

Slides and docs copy numbers from results/key_numbers.md only, so a rerun that changes a result
shows up in one place and nothing is typed by hand.
"""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))  # import common.py from any working dir
from common import RESULTS  # noqa: E402


def load(name):
    return json.loads((RESULTS / name).read_text())


def usd(x):
    return f"-${-x:,.0f}" if x < 0 else f"${x:,.0f}"


def pct(x, digits=0):
    return f"{100 * x:.{digits}f}%"


def main():
    a1 = load("act1_summary.json")
    dq = load("college_data_quality.json")
    m = load("college_metrics.json")
    opp = load("opportunity_summary.json")
    b20 = pd.read_csv(RESULTS / "bottom20_by_measure.csv").set_index("group")
    sens = pd.read_csv(RESULTS / "race_sensitivity.csv").set_index("group")
    err = pd.read_csv(RESULTS / "errors_by_group.csv")
    imp = pd.read_csv(RESULTS / "feature_importance.csv")

